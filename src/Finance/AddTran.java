    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String amountText = txtAmount.getText();
        String category = cmbCategory.getSelectedItem().toString();
        String description = txtDescription.getText();

        if (amountText.isEmpty() || description.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill in all fields!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            int amount = Integer.parseInt(amountText);
            String type = category; // "Income" atau "Expense"

            AddTran.addTransaction(type, amount, category, description);

            JOptionPane.showMessageDialog(null, "Transaction Added Successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);

            // Update balance di FinanceManage
            mainFrame.updateBalance();

            // Kosongkan input setelah transaksi berhasil ditambahkan
            txtAmount.setText("");
            txtDescription.setText("");

        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(null, "Invalid Amount!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

