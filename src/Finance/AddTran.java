    public static void addTransaction(String type, int amount, String category, String description) {
    // Simpan dalam format "Expense:200000:Food:Beli makan"
    String transaction = type + ":" + amount + ":" + category + ":" + description;
    transactionHistory.add(transaction);
}
    
    public static ArrayList<String> getTransactionHistory() {
    return transactionHistory;
}

